export function searchPlaces(query:string,limit=6):Place[]{
 const q=query.trim().toLowerCase();
 if(q.length<2)return [];
 const hits:{place:Place;score:number}[]=[];
 for(const place of places){
  const names=[place.name,place.state,...(place.aliases??[])].map(name=>name.toLowerCase());
  const score=names.some(name=>name===q)?3:names.some(name=>name.startsWith(q))?2:names.some(name=>name.includes(q))?1:0;
  if(score)hits.push({place,score});
 }
 return hits.sort((a,b)=>b.score-a.score).slice(0,limit).map(hit=>hit.place);
}
